-- ===========================================================================
-- Get Home Realty — admin / CMS schema (PostgreSQL 15+; Supabase compatible)
-- Idempotent: safe to run on every deploy (`npm run db:migrate`).
-- ===========================================================================

-- ---------- admins & auth ----------
create table if not exists admins (
  id             integer generated by default as identity primary key,
  email          text not null unique,
  name           text not null default '',
  password_hash  text not null,
  role           text not null default 'admin' check (role in ('admin', 'editor')),
  is_active      boolean not null default true,
  failed_logins  integer not null default 0,
  locked_until   timestamptz,
  last_login_at  timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- Session id = SHA-256 of the random cookie token (the raw token is never stored).
create table if not exists sessions (
  id           text primary key,
  admin_id     integer not null references admins(id) on delete cascade,
  csrf_token   text not null,
  expires_at   timestamptz not null,
  created_at   timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  ip           text,
  user_agent   text
);
create index if not exists sessions_admin_idx on sessions(admin_id);

create table if not exists password_resets (
  id          text primary key,             -- SHA-256 of the emailed token
  admin_id    integer not null references admins(id) on delete cascade,
  expires_at  timestamptz not null,
  used_at     timestamptz,
  created_at  timestamptz not null default now()
);

