-- Backfill slugs for agents/videos created before slugs existed (dupes get "-<id>").
update agents set slug = trim(both '-' from regexp_replace(lower(name), '[^a-z0-9]+', '-', 'g')) where slug is null or slug = '';
update agents a set slug = a.slug || '-' || a.id where exists (select 1 from agents b where b.slug = a.slug and b.id < a.id);
update videos set slug = trim(both '-' from regexp_replace(lower(title), '[^a-z0-9]+', '-', 'g')) where slug is null or slug = '';
update videos a set slug = a.slug || '-' || a.id where exists (select 1 from videos b where b.slug = a.slug and b.id < a.id);
