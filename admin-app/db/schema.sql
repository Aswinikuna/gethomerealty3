create table if not exists projects (
  id              integer generated by default as identity primary key,
  slug            text not null unique,      -- matches GHR_DETAILS keys on the public site
  name            text not null,
  developer       text,
  city            text,
  location        text,                      -- locality, e.g. "Kokapet"
  starting_price  text,                      -- display, e.g. "₹7,500/sq.ft"
  price_from      double precision,          -- numeric, for sorting / price filters
  property_type   text,
  unit_sizes      text,
  bedrooms        text,                      -- e.g. "2, 3 & 4 BHK"
  possession      text,
  description     text,
  amenities       jsonb not null default '[]'::jsonb,
  main_image      text,
  brochure_url    text,
  video_url       text,
  map_url         text,
  lat             double precision,
  lng             double precision,
  status          text not null default 'selling' check (status in ('upcoming','selling','sold_out')),
  is_published    boolean not null default true,
  is_featured     boolean not null default false,
  display_order   integer not null default 0,
  extra           jsonb not null default '{}'::jsonb,   -- legacy directory fields (scale, exp, phone, website…)
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  created_by      integer references admins(id) on delete set null,
  updated_by      integer references admins(id) on delete set null
);
create index if not exists projects_list_idx on projects(is_published, display_order, id);

create table if not exists project_images (
  id          integer generated by default as identity primary key,
  project_id  integer not null references projects(id) on delete cascade,
  kind        text not null default 'gallery' check (kind in ('gallery','floorplan')),
  url         text not null,
  alt         text,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);
create index if not exists project_images_fk on project_images(project_id, kind, sort_order);

