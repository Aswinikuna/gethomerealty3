-- ---------- leads ----------
create table if not exists leads (
  id               integer generated by default as identity primary key,
  name             text not null,
  phone            text,
  email            text,
  message          text,
  inquiry_type     text,
  property_id      integer references properties(id) on delete set null,
  project_id       integer references projects(id) on delete set null,
  reference_label  text,                      -- human-readable property/project reference
  source           text,                      -- page the form was submitted from
  details          jsonb not null default '{}'::jsonb,   -- any extra form fields (budget, timeline…)
  status           text not null default 'new'
                   check (status in ('new','contacted','follow_up','qualified','closed','lost')),
  ip               text,
  user_agent       text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists leads_status_idx on leads(status, created_at desc);
create index if not exists leads_created_idx on leads(created_at desc);

create table if not exists lead_notes (
  id          integer generated by default as identity primary key,
  lead_id     integer not null references leads(id) on delete cascade,
  admin_id    integer references admins(id) on delete set null,
  note        text not null,
  created_at  timestamptz not null default now()
);
create index if not exists lead_notes_fk on lead_notes(lead_id, created_at);

